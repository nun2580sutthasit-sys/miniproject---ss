CREATE TABLE IF NOT EXISTS support_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  category VARCHAR(20) NOT NULL
    CHECK (category IN ('account', 'order', 'product', 'other')),
  subject VARCHAR(160) NOT NULL,
  message VARCHAR(2000) NOT NULL CHECK (length(message) BETWEEN 1 AND 2000),
  status VARCHAR(16) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_progress', 'resolved', 'rejected')),
  admin_note VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by BIGINT REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS idx_support_requests_status
  ON support_requests (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_requests_user
  ON support_requests (user_id, created_at DESC);
